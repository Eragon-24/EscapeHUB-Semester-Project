CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_user_username_lower
    ON user_account (LOWER(username));

CREATE UNIQUE INDEX uq_user_email_lower
    ON user_account (LOWER(email));


CREATE TABLE team (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    join_code VARCHAR(6) NOT NULL UNIQUE
);

CREATE TABLE team_member (
    team_id BIGINT NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('CREATOR', 'MEMBER')),
    PRIMARY KEY (team_id, user_id)
);

CREATE UNIQUE INDEX uq_team_one_creator
    ON team_member(team_id)
    WHERE role = 'CREATOR';


CREATE TABLE game_session (
    id UUID PRIMARY KEY,
    join_code VARCHAR(6) NOT NULL UNIQUE,
    creator_user_id BIGINT NOT NULL REFERENCES user_account(id),
    status VARCHAR(20) NOT NULL DEFAULT 'LOBBY'
        CHECK (status IN ('LOBBY', 'ACTIVE', 'COMPLETED', 'TERMINATED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    end_reason VARCHAR(30)
        CHECK (end_reason IN ('MISSION_COMPLETED', 'CREATOR_ENDED')),
    CHECK (started_at IS NULL OR ended_at IS NULL OR started_at <= ended_at)
);

CREATE TABLE session_participant (
    session_id UUID NOT NULL REFERENCES game_session(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES user_account(id),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ,
    PRIMARY KEY (session_id, user_id),
    CHECK (left_at IS NULL OR left_at >= joined_at)
);


CREATE TABLE game_state (
    session_id UUID PRIMARY KEY REFERENCES game_session(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL DEFAULT 'IN_PROGRESS',
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);

CREATE TABLE game_attribute (
    session_id UUID NOT NULL REFERENCES game_session(id) ON DELETE CASCADE,
    attribute_key VARCHAR(64) NOT NULL,
    attribute_value VARCHAR(1000) NOT NULL,
    PRIMARY KEY (session_id, attribute_key)
);


CREATE TABLE session_player_positions (
    session_id UUID NOT NULL,
    user_id BIGINT NOT NULL,
    room_id VARCHAR(100) NOT NULL,
    position_x DOUBLE PRECISION NOT NULL,
    position_y DOUBLE PRECISION NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (session_id, user_id),
    FOREIGN KEY (session_id, user_id)
        REFERENCES session_participant(session_id, user_id)
        ON DELETE CASCADE
);


CREATE TABLE participant_connection_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL,
    user_id BIGINT NOT NULL,
    connected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    disconnected_at TIMESTAMPTZ,
    FOREIGN KEY (session_id, user_id)
        REFERENCES session_participant(session_id, user_id)
        ON DELETE CASCADE,
    CHECK (disconnected_at IS NULL OR disconnected_at >= connected_at)
);

CREATE UNIQUE INDEX uq_participant_open_connection
    ON participant_connection_history(session_id, user_id)
    WHERE disconnected_at IS NULL;

CREATE INDEX idx_session_participant_user
    ON session_participant(user_id);

CREATE INDEX idx_connection_history_user
    ON participant_connection_history(user_id);

CREATE INDEX idx_game_session_creator
    ON game_session(creator_user_id);
